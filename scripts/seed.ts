async function seed() {
  console.log(`准备导入案例总数：${seedCases.length}`);

  // 获取库内已有的title，做去重，避免重复插入
  const { data: existData } = await supabase.from("cases").select("title");
  const existTitles = new Set(existData?.map(item => item.title) ?? []);

  const newItems = seedCases.filter(item => !existTitles.has(item.title));

  if(newItems.length === 0){
    console.log("✅所有案例已经存在数据库，无需插入");
    return;
  }

  console.log(`本次实际新增案例：${newItems.length}`);
  const { error } = await supabase.from("cases").insert(newItems);

  if(error){
    console.error("❌插入案例出错：", error);
    process.exit(1);
  }

  console.log("✅seed案例插入完成！");
  console.log("👉下一步执行命令生成向量：npx tsx scripts/embed.ts");
}

seed().catch(err => {
  console.error(err);
  process.exit(1);
});
